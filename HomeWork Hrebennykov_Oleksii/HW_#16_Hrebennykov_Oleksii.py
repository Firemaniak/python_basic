# -----------Правильные скобки-------------
# Напишите программу, которая принимает строку, содержащую любые виды скобок — круглые (), квадратные [] и фигурные {}.
# Необходимо проверить, правильно ли они расставлены. Скобки считаются правильно расставленными, если:
# -Каждая открывающая скобка имеет соответствующую закрывающую.
# -Скобки закрываются в правильном порядке.

# Пример данных:
# string = "({[}])"
#
# Пример вывода:
#
# Скобки: ({[}])
# Валидны: False
#
# Скобки: ([({}()){}])
# Валидны: True


string = input("Введите строку: ")
stack = []
is_valid = True

for item in string:
    if item == "(" or item == "[" or item == "{":
        stack.append(item)
    else:
        if not stack:
            is_valid = False
            break

        last = stack[-1]
        if item == ")" and last == "(":
            stack.pop()
        elif item == "]" and last == "[":
            stack.pop()
        elif item == "}" and last == "{":
            stack.pop()
        else:
            is_valid = False
            break
if is_valid and len(stack) == 0:
    print("Скобки: ", string)
    print(True)
else:
    print("Скобки: ", string)
    print(False)