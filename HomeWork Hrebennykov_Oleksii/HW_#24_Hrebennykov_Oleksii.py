#------------------------------------------Сумма вложенных чисел--------------------------------------------------------
# Напишите рекурсивную функцию, которая суммирует все числа во вложенных списках.
#
# Данные:
# nested_numbers = [1, [2, 3], [4, [5, 6]], 7]
# Пример вывода:
# 28

nested_numbers = [1, [2, 3], [4, [5, 6]], 7]

def sum_nested(data: list) -> int:

    """
    Рекурсивно суммирует все числа во вложенных списках.

    :param data: Список с числами и вложенными списками
    :return: Сумма всех чисел
    """

    total = 0
    for item in data:
        if isinstance(item, list):
            total += sum_nested(item)
        else:
            total += item
    return total

print(sum_nested(nested_numbers))

