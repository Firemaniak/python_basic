#----------------------------------------------Сумма цифр числа---------------------------------------------------------
# Напишите рекурсивную функцию, которая находит сумму всех цифр числа.

# Данные:
num = 43197
# Пример вывода:
# 24

def sum_number(num: int) -> int:

    """
    Рекурсивно находит сумму всех цифр числа.

    :param num: Целое число.
    :return: Сумма цифр.
    """

    if num == 0:
        return 0
    return num % 10 + sum_number(num // 10)

print(sum_number(num))

