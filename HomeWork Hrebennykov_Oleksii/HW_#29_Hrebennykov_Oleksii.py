#------------------------------------------Генератор уникальных элементов-----------------------------------------------

# Создайте генератор, который принимает список элементов и выдаёт только уникальные значения,
# сохраняя порядок их появления в исходном списке.
#
# Данные:
#
data = [3, 1, 2, 3, 4, 1, 5, 2, 6, 7, 5, 8]
#
# Пример вывода:
#
# 3
# 1
# 2
# 4
# 5
# 6
# 7
# 8

def unique_values(items):
    """
    Generate only unique values while preserving order.
    """

    seen = set()

    for item in items:
        if item not in seen:
            seen.add(item)
            yield item


gen = unique_values(data)

for number in gen:
    print(number)

