# Через словарь

count_dict = {}
for item in numbers:
    if item in count_dict:
        count_dict[item] += 1
    else:
        count_dict[item] = 1

result = []

for key in count_dict:
    if count_dict[key] > 1:
        result.append(key)

result = sorted(result, reverse=True)
