# Проверка подмножества
# Задача: Напишите программу, которая проверяет, является ли один словарь подмножеством другого
# (т.е. все его пары "ключ-значение" содержатся в другом словаре).

# Данные:
dict1 = {"a": 1, "b": 2}
dict2 = {"a": 1, "b": 2, "c": 3}

# Пример вывода:
# Первый словарь является подмножеством второго.

is_subset = True

for key in dict1:
    if key not in dict2 or dict1[key] != dict2[key]:
        is_subset = False
        break
if is_subset:
    print('Первый словарь является подмножеством второго.')
else:
    print('Не является подмножеством.')


